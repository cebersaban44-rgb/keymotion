const messages: Record<Locale, Record<MessageKey, string>> = { tr, en };

/** "%40" in Turkish, "40%" in English. */
export function percent(n: number) {
  return useApp.getState().locale === "tr" ? `%${n}` : `${n}%`;
}

/** "2,8" in Turkish, "2.8" in English. */
export function decimal(n: number, digits = 1) {
  return n.toLocaleString(useApp.getState().locale === "tr" ? "tr-TR" : "en-US", { maximumFractionDigits: digits });
}

/** Values for a message's `{name}` placeholders. */
export type MessageVars = Record<string, string | number>;
export type Translate = (key: MessageKey, vars?: MessageVars) => string;

/**
 * The message for `key` with each `{name}` replaced by `vars.name`.
 * Counts: when `vars.count` is 1 and the key has a `.one` form, that form is
 * used ("1 frame"). Turkish keeps a single form after numbers, so its `.one`
 * text is the same as the plural one.
 */
function message(locale: Locale, key: MessageKey, vars?: MessageVars) {
  const table = messages[locale];
  if (!vars) return table[key];
  const text = (vars.count === 1 && table[`${key}.one` as MessageKey]) || table[key];
  return text.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all));
}

/** Translate outside React (current locale at call time). */
export function tNow(key: MessageKey, vars?: MessageVars) {
  return message(useApp.getState().locale, key, vars);
}

export function useT(): Translate {
  const locale = useApp((s) => s.locale);
  return (key, vars) => message(locale, key, vars);
}

export const connectionKey = (c: Connection, short = false): MessageKey =>
  `conn.${c}${short ? ".short" : ""}` as MessageKey;

export const featureKey = (f: Feature): MessageKey => `feature.${f}` as MessageKey;

export function useAgo() {
  const t = useT();
  return (ms: number) => {
    const s = Math.max(0, Math.round((Date.now() - ms) / 1000));
    if (s < 60) return `${s} ${t("time.s")}`;
    const m = Math.round(s / 60);
    if (m < 60) return `${m} ${t("time.m")}`;
    const h = Math.round(m / 60);
    if (h < 48) return `${h} ${t("time.h")}`;
    return `${Math.round(h / 24)} ${t("time.d")}`;
  };
}
